# строковые константы для значений NEEDPRO* — чтобы сравнивать
# по идентификатору, а не по содержимому подстроки
NEEDPRO_YES = "Да"
NEEDPRO_NO = "Нет"
NEEDPRO_BLOCKED = "Нужен, но бюджет не позволяет — упростите проект"


class TileExpertSystem:
    """
    Экспертная система "Выбор способа укладки плитки".

    Все цепочки сходятся к ОДНОМУ итоговому выводу SOLUTION*,
    который объединяет способ укладки, клей и затирку.

    Уровень 1*: DIFFIC, ELAST, WETENV
    Уровень 2*: SKILLREQ, GLUECLASS, HYDRO, COSTLEVEL
    Уровень 3*: NEEDPRO, BUDGETFIT
    Уровень 4*: LAYPAT, GLUE, GROUT
    Уровень 5* (ИТОГ): SOLUTION  — единая рекомендация
    Доп.:        WARNINGS — конфликты входных данных.
    """

    def __init__(self):
        self.facts = {}
        self.derived = {}  # промежуточные выводы со *
        self.warnings = []

    # ============================================================
    # Вспомогательный ввод
    # ============================================================
    def ask(self, question: str, options: list) -> str:
        print(f"\n{question}")
        for i, opt in enumerate(options, 1):
            print(f"  {i}. {opt}")
        while True:
            try:
                choice = int(input("   Ваш выбор (номер): "))
                if 1 <= choice <= len(options):
                    selected = options[choice - 1]
                    print(f"   → Выбрано: {selected}")
                    return selected
                print("   Ошибка: введите номер из списка!")
            except ValueError:
                print("   Ошибка: введите число!")

    # ============================================================
    # СБОР ВХОДНЫХ ДАННЫХ
    # ============================================================
    def collect_input(self):
        print("=" * 100)
        print("   ЭКСПЕРТНАЯ СИСТЕМА: Выбор способа укладки плитки")
        print("=" * 100)

        f = self.facts
        f['surface'] = self.ask("1. Тип поверхности",
            ["Пол", "Стена", "Потолок"])
        f['base_material'] = self.ask("2. Материал основания",
            ["Бетон", "Гипсокартон", "Дерево/ДСП",
             "Штукатурка", "Металл"])
        f['base_condition'] = self.ask("3. Состояние основания",
            ["Идеально ровное", "С небольшими неровностями",
             "С трещинами/дефектами",
             "Требует капитального выравнивания"])
        f['room_type'] = self.ask("4. Тип помещения",
            ["Ванная/санузел", "Кухня", "Гостиная/коридор",
             "Балкон/лоджия", "Наружные работы"])
        f['humidity'] = self.ask("5. Уровень влажности",
            ["Сухое помещение", "Влажное",
             "Мокрое (постоянный контакт с водой)"])
        f['tile_type'] = self.ask("6. Тип плитки",
            ["Керамика", "Керамогранит", "Мозаика", "Клинкер"])
        f['tile_size'] = self.ask("7. Размер плитки",
            ["Маленькая (до 20×20 см)", "Средняя (20–40 см)",
             "Большая (свыше 40 см)"])
        f['pattern'] = self.ask("8. Желаемый рисунок укладки",
            ["Прямая", "Диагональная", "Елочкой",
             "Со смещением", "Модульная"])
        f['experience'] = self.ask("9. Уровень опыта укладчика",
            ["Новичок", "Средний", "Профессионал"])
        f['budget'] = self.ask("10. Бюджет",
            ["Низкий", "Средний", "Высокий"])
        f['area'] = self.ask("11. Площадь укладки",
            ["До 5 м²", "5–15 м²", "15–30 м²", "Более 30 м²"])
        f['tile_shape'] = self.ask("12. Форма плитки",
            ["Квадрат", "Прямоугольник", "Шестигранник"])

        if f['surface'] == "Пол":
            f['warm_floor'] = self.ask("13. Есть ли тёплый пол?",
                ["Да", "Нет"])
            f['load'] = self.ask("14. Ожидаемая нагрузка",
                ["Низкая (пешеходная)", "Средняя", "Высокая"])
        else:
            f['warm_floor'] = "Нет"
            f['load'] = "Низкая (пешеходная)"

        f['joint_width'] = self.ask("15. Ширина швов",
            ["Тонкие (1–2 мм)", "Средние (3–5 мм)",
             "Широкие (более 5 мм)"])
        f['adhesion'] = self.ask("16. Адгезия основания",
            ["Высокая", "Средняя", "Низкая (требует грунтовки)"])
        f['temp_mode'] = self.ask("17. Температурный режим",
            ["Стандартный (18–25°C)", "Низкие температуры",
             "Высокие температуры"])
        f['style'] = self.ask("18. Стиль дизайна",
            ["Современный", "Классический", "Минимализм"])
        f['allergy_eco'] = self.ask(
            "19. Аллергия на химию или важна экологичность?",
            ["Да", "Нет"])

        # outdoor выводится из room_type без отдельного вопроса
        f['outdoor'] = ("Наружные"
                       if f['room_type'] == "Наружные работы"
                       else "Внутренние")
        # frost выводится из outdoor + temp_mode
        f['frost'] = ("Да"
                      if f['outdoor'] == "Наружные"
                         or f['temp_mode'] == "Низкие температуры"
                      else "Нет")

        print("\n" + "=" * 100)

    # ============================================================
    # УРОВЕНЬ 1 промежуточных выводов
    # ============================================================
    def _derive_diffic(self):
        """DIFFIC* — объективная сложность рисунка укладки.
        Зависит только от рисунка, размера и формы плитки.
        Опыт укладчика учитывается ниже через SKILLREQ → NEEDPRO."""
        f = self.facts
        hard_patterns = {"Диагональная", "Елочкой", "Модульная"}
        if f['pattern'] in hard_patterns \
                or f['tile_size'] == "Большая (свыше 40 см)":
            level = "Высокая"
        elif f['pattern'] == "Со смещением" \
                or f['tile_size'] == "Средняя (20–40 см)":
            level = "Средняя"
        else:
            level = "Низкая"
        # шестигранник сам по себе усложняет раскладку
        if f['tile_shape'] == "Шестигранник" and level == "Низкая":
            level = "Средняя"
        self.derived['DIFFIC'] = level
        return level

    def _derive_elast(self):
        """ELAST* — нужна ли эластичность клея.
        Влияют: материал основания, тёплый пол, мороз/наружка,
        формат плитки, тип плитки, нагрузка, состояние основания."""
        f = self.facts
        big_tile = f['tile_size'] == "Большая (свыше 40 см)"
        low_absorb = f['tile_type'] in ("Керамогранит", "Клинкер")

        # Безусловно обязательна: деформирующиеся/подвижные основания,
        # тёплый пол, морозные/наружные условия, большой керамогранит
        if f['base_material'] == "Дерево/ДСП" \
                or f['warm_floor'] == "Да" \
                or f['frost'] == "Да" \
                or (big_tile and low_absorb):
            val = "Обязательна"
        # Желательна: пограничные основания и условия повышенных
        # напряжений на клеевой шов
        elif f['base_material'] in ("Гипсокартон", "Металл") \
                or big_tile \
                or f['load'] == "Высокая" \
                or f['base_condition'] in (
                    "С трещинами/дефектами",
                    "Требует капитального выравнивания"):
            val = "Желательна"
        else:
            val = "Не требуется"
        self.derived['ELAST'] = val
        return val

    def _derive_wetenv(self):
        """WETENV* — степень влажности среды."""
        f = self.facts
        if f['humidity'] == "Мокрое (постоянный контакт с водой)" \
                or f['room_type'] == "Ванная/санузел":
            val = "Мокрая"
        elif f['humidity'] == "Влажное" \
                or f['room_type'] == "Кухня":
            val = "Влажная"
        else:
            val = "Сухая"
        self.derived['WETENV'] = val
        return val

    # ============================================================
    # УРОВЕНЬ 2 промежуточных выводов
    # ============================================================
    def _derive_skillreq(self):
        """SKILLREQ* — требуемый уровень мастерства.
        Строится из DIFFIC и AREA."""
        diffic = self.derived['DIFFIC']
        area = self.facts['area']
        big_area = area in ("15–30 м²", "Более 30 м²")
        if diffic == "Высокая" or (diffic == "Средняя" and big_area):
            val = "Высокий"
        elif diffic == "Средняя" or big_area:
            val = "Средний"
        else:
            val = "Низкий"
        self.derived['SKILLREQ'] = val
        return val

    def _derive_glueclass(self):
        """GLUECLASS* — класс клея. Из ELAST, TILETYP, LOAD, ADHES и BUDGET.
        Бюджет может смягчить требования там, где это безопасно,
        но НЕ может отменить эластичный клей, усиленный класс для
        нагрузок и низковпитывающей плитки, либо повышенный класс
        при плохой адгезии основания."""
        elast = self.derived['ELAST']
        tile = self.facts['tile_type']
        load = self.facts['load']
        adhes = self.facts['adhesion']
        budget = self.facts['budget']

        low_adhes = adhes == "Низкая (требует грунтовки)"

        if elast == "Обязательна":
            val = "Эластичный"  # компромиссов нет — иначе плитка отвалится
        elif tile in ("Керамогранит", "Клинкер") or load == "Высокая":
            # низкое водопоглощение или высокая нагрузка требуют C2T
            val = "Усиленный"
        elif elast == "Желательна" or low_adhes:
            # проблемные основания требуют клей повышенной адгезии (C2)
            val = "Улучшенный"
        else:
            val = "Стандартный"

        # при низком бюджете и отсутствии критических условий
        # допустимо упростить класс клея
        # (любая нагрузка выше пешеходной блокирует упрощение)
        if budget == "Низкий" and elast == "Не требуется" \
                and tile not in ("Керамогранит", "Клинкер") \
                and load == "Низкая (пешеходная)" \
                and not low_adhes:
            val = "Стандартный"

        self.derived['GLUECLASS'] = val
        return val

    def _derive_hydro(self):
        """HYDRO* — требуется ли гидроизоляция.
        Из WETENV, OUTDOOR, материала основания, типа помещения
        и наличия тёплого пола."""
        f = self.facts
        wet = self.derived['WETENV']
        outdoor = f['outdoor']
        base = f['base_material']
        water_sensitive = base in ("Дерево/ДСП", "Гипсокартон")

        # Обязательна: прямой контакт с водой / улица / влагочувствительный
        # материал во влажной зоне
        if wet == "Мокрая" or outdoor == "Наружные":
            val = "Обязательна"
        elif water_sensitive and wet == "Влажная":
            val = "Обязательна"
        # Желательна: повышенная влажность, влагочувствительное основание
        # даже в сухом помещении, балкон/лоджия, тёплый пол
        elif wet == "Влажная" \
                or base == "Дерево/ДСП" \
                or f['room_type'] == "Балкон/лоджия" \
                or f['warm_floor'] == "Да":
            val = "Желательна"
        else:
            val = "Не нужна"
        self.derived['HYDRO'] = val
        return val

    def _derive_costlevel(self):
        """COSTLEVEL* — ориентировочный уровень стоимости проекта.
        Считается по сумме факторов удорожания: тип/размер плитки,
        сложность рисунка, площадь, требования к клею и гидроизоляции."""
        f = self.facts
        score = 0
        # тип плитки
        score += {"Керамика": 0, "Мозаика": 3,
                  "Керамогранит": 2, "Клинкер": 2}[f['tile_type']]
        # размер плитки: маленькая = много подрезки и швов;
        # большая уже учтена через DIFFIC, отдельно не считаем
        score += {"Маленькая (до 20×20 см)": 1,
                  "Средняя (20–40 см)": 0,
                  "Большая (свыше 40 см)": 0}[f['tile_size']]
        # сложность рисунка
        score += {"Низкая": 0, "Средняя": 1, "Высокая": 3}[self.derived['DIFFIC']]
        # площадь (масштаб расходов на материалы)
        score += {"До 5 м²": 0, "5–15 м²": 1,
                  "15–30 м²": 2, "Более 30 м²": 3}[f['area']]
        # класс клея
        score += {"Стандартный": 0, "Улучшенный": 1,
                  "Усиленный": 2, "Эластичный": 2}[self.derived['GLUECLASS']]
        # гидроизоляция
        score += {"Не нужна": 0, "Желательна": 1, "Обязательна": 2}[self.derived['HYDRO']]
        # морозостойкость / тёплый пол — спец-составы
        if f['frost'] == "Да":
            score += 1
        if f['warm_floor'] == "Да":
            score += 1

        if score <= 3:
            val = "Низкая"
        elif score <= 7:
            val = "Средняя"
        else:
            val = "Высокая"
        self.derived['COSTLEVEL'] = val
        return val

    # ============================================================
    # УРОВЕНЬ 3 промежуточных выводов
    # ============================================================
    def _derive_budgetfit(self):
        """BUDGETFIT* — соответствие бюджета стоимости проекта.
        Сравнивает COSTLEVEL с BUDGET. Если стоимость выше бюджета
        хотя бы на одну ступень — бюджета уже недостаточно."""
        cost = self.derived['COSTLEVEL']
        budget = self.facts['budget']
        rank = {"Низкий": 0, "Низкая": 0,
                "Средний": 1, "Средняя": 1,
                "Высокий": 2, "Высокая": 2}
        if rank[cost] <= rank[budget]:
            val = "Достаточно"
        else:
            val = "Недостаточно"
        self.derived['BUDGETFIT'] = val
        return val

    def _derive_needpro(self):
        """NEEDPRO* — нужен ли профессионал.
        Учитывает требуемый уровень мастерства, опыт исполнителя
        И возможность нанять профи (BUDGETFIT)."""
        skill = self.derived['SKILLREQ']
        exp = self.facts['experience']
        fit = self.derived['BUDGETFIT']

        # сначала чисто техническая потребность
        if skill == "Высокий" and exp != "Профессионал":
            need = NEEDPRO_YES
        elif skill == "Средний" and exp == "Новичок":
            need = NEEDPRO_YES
        else:
            need = NEEDPRO_NO

        # теперь учёт бюджета: профи стоит денег
        if need == NEEDPRO_YES and fit == "Недостаточно":
            val = NEEDPRO_BLOCKED
        else:
            val = need

        self.derived['NEEDPRO'] = val
        return val

    # ============================================================
    # WARNINGS* — обнаружение конфликтов входных данных
    # ============================================================
    def _derive_warnings(self):
        """WARNINGS* — список несовместимых/опасных комбинаций."""
        f = self.facts
        w = []

        # материал основания vs поверхность
        if f['surface'] == "Пол" and f['base_material'] == "Гипсокартон":
            w.append("Гипсокартон не подходит для пола — нужна стяжка или ЦСП.")
        if f['surface'] == "Пол" and f['base_material'] == "Металл":
            w.append("Металлическое основание под полом — нетипично; "
                     "обязательна антикоррозийная обработка и эластичный клей.")
        if f['surface'] == "Потолок" \
                and f['tile_size'] == "Большая (свыше 40 см)":
            w.append("Крупная плитка на потолке опасна — высок риск отрыва. "
                     "Используйте маленький/средний формат и механическое крепление.")
        if f['surface'] == "Потолок" and f['tile_type'] == "Керамогранит":
            w.append("Керамогранит на потолке — большой вес; "
                     "проверьте несущую способность и применяйте страховочный крепёж.")

        # дерево/влага
        if f['base_material'] == "Дерево/ДСП" \
                and self.derived['WETENV'] in ("Мокрая", "Влажная"):
            w.append("Дерево/ДСП во влажной среде — рискованно. "
                     "Обязательны гидроизоляция, эластичный клей и пароизоляция.")

        # наружка и плитка
        if f['outdoor'] == "Наружные" \
                and f['tile_type'] == "Керамика":
            w.append("Обычная керамика не подходит для улицы — "
                     "используйте керамогранит или клинкер (морозостойкие).")
        if f['outdoor'] == "Наружные" and f['tile_type'] == "Мозаика":
            w.append("Мозаика на улице требует особо стойких составов; "
                     "обычно нецелесообразно из-за стоимости и швов.")

        # высокая нагрузка vs тип плитки
        if f['load'] == "Высокая" and f['tile_type'] == "Керамика":
            w.append("Обычная керамика не рассчитана на высокую нагрузку — "
                     "возьмите керамогранит или клинкер.")

        # площадь / швы
        if f['tile_size'] == "Большая (свыше 40 см)" \
                and f['joint_width'] == "Тонкие (1–2 мм)":
            w.append("Большая плитка с тонкими швами требует идеально ровного основания "
                     "и калиброванной плитки — иначе появятся «ступеньки».")

        # форма vs рисунок: шестигранник несовместим с ёлочкой/диагональю;
        # «прямая» для шестигранника = классические соты, это норма
        if f['tile_shape'] == "Шестигранник" \
                and f['pattern'] in ("Елочкой", "Диагональная"):
            w.append("Шестигранник плохо сочетается с диагональной/ёлочной "
                     "раскладкой — естественны соты или модульная.")

        # бюджет vs проект (общее)
        if self.derived['BUDGETFIT'] == "Недостаточно":
            w.append("Бюджет ниже стоимости проекта. "
                     "Рассмотрите упрощения: керамика вместо керамогранита, "
                     "стандартный рисунок, средний размер плитки, цементная затирка.")

        # основание требует капитального выравнивания
        if f['base_condition'] == "Требует капитального выравнивания":
            w.append("Основание требует капитального выравнивания — "
                     "перед укладкой нужна стяжка (для пола) или "
                     "штукатурка/ГВЛ (для стен). Заложите время и бюджет на эти работы.")

        self.warnings = w
        return w

    # ============================================================
    # УРОВЕНЬ 4 — ИТОГОВЫЕ ВЫВОДЫ
    # ============================================================
    def _infer_laypat(self):
        """LAYPAT* — способ укладки.
        Учитывает потребность в профи, опыт и состояние основания.
        Бюджет уже учтён через NEEDPRO (BUDGETFIT)."""
        f = self.facts
        needpro = self.derived['NEEDPRO']
        hard = ("Диагональная", "Елочкой", "Модульная")

        # если бюджета не хватает на профи — упрощаем сложный рисунок
        if needpro == NEEDPRO_BLOCKED:
            if f['pattern'] in hard:
                return "Прямая (вынужденное упрощение: профи недоступен)"
            return f['pattern'] + " (без привлечения профи)"

        # профи доступен и нужен — берём задуманный рисунок
        if needpro == NEEDPRO_YES:
            return f['pattern']

        # новичок без необходимости в профи — не берётся за сложное
        if f['experience'] == "Новичок" and f['pattern'] in hard:
            return "Прямая (упрощение сложного рисунка для новичка)"

        # минимализм на ровной основе → прямая
        if f['base_condition'] == "Идеально ровное" \
                and f['style'] == "Минимализм":
            return "Прямая"

        return f['pattern']

    def _infer_glue(self):
        """GLUE* — конкретный тип клея.
        Учитывает влажность, температуру, мороз и адгезию.
        Нагрузка уже учтена в GLUECLASS."""
        f = self.facts
        gclass = self.derived['GLUECLASS']
        wet = self.derived['WETENV']

        # высокие температуры (камин, сауна, тёплая стена) — термостойкий
        if f['temp_mode'] == "Высокие температуры":
            base = "Термостойкий (" + gclass.lower() + ")"
        # мороз + мокрая среда (фасад, терраса под дождём)
        elif f['frost'] == "Да" and wet == "Мокрая":
            base = "Морозостойкий влагостойкий (на базе " + gclass.lower() + ")"
        # морозостойкость (наружка / низкие температуры)
        elif f['frost'] == "Да":
            base = "Морозостойкий (" + gclass.lower() + ")"
        elif wet == "Мокрая":
            base = "Для влажных помещений (на базе " + gclass.lower() + ")"
        elif f['temp_mode'] == "Низкие температуры":
            base = "Быстросохнущий (" + gclass.lower() + ")"
        else:
            base = gclass

        # грунтовка: ВСЕГДА при низкой адгезии; для невпитывающей
        # плитки (керамогранит/клинкер) — также при средней адгезии
        if f['adhesion'] == "Низкая (требует грунтовки)":
            base += " + грунтовка"
        elif f['adhesion'] == "Средняя" \
                and f['tile_type'] in ("Керамогранит", "Клинкер"):
            base += " + грунтовка (рекомендуется)"

        return base

    def _infer_grout(self):
        """GROUT* — тип затирки.
        Учитывает гидроизоляцию, мороз, ширину швов, экологию и бюджет."""
        f = self.facts
        hydro = self.derived['HYDRO']
        budget = f['budget']

        # обязательные эпоксидные случаи нельзя отменить бюджетом
        if hydro == "Обязательна" or f['frost'] == "Да":
            if budget == "Низкий":
                return "Эпоксидная (рекомендуется; готовьте дополнительный бюджет)"
            return "Эпоксидная"

        # гигиена/влага приоритетнее декоративности
        if hydro == "Желательна" or f['allergy_eco'] == "Да":
            if f['joint_width'] == "Широкие (более 5 мм)":
                return "Антигрибковая для широких швов"
            return "Антигрибковая"

        if f['joint_width'] == "Широкие (более 5 мм)":
            # декоративные дорогие — при низком бюджете обычная для широких швов
            if budget == "Низкий":
                return "Цементная для широких швов"
            return "Декоративная"

        return "Цементная"

    # ============================================================
    # УРОВЕНЬ 5 — ЕДИНЫЙ ИТОГ
    # ============================================================
    def _infer_solution(self, laypat, glue, grout):
        """SOLUTION* — единый итоговый ответ системы.
        Сводит LAYPAT, GLUE и GROUT в одну рекомендацию."""
        return (f"Уложить «{laypat}»; "
                f"клей — {glue}; "
                f"затирка — {grout}.")

    # ============================================================
    # Главный метод вывода
    # ============================================================
    def infer(self):
        # уровень 1
        self._derive_diffic()
        self._derive_elast()
        self._derive_wetenv()
        # уровень 2
        self._derive_skillreq()
        self._derive_glueclass()
        self._derive_hydro()
        self._derive_costlevel()
        # уровень 3
        self._derive_budgetfit()
        self._derive_needpro()
        # обнаружение конфликтов входных данных
        self._derive_warnings()
        # уровень 4 (промежуточные итоги)
        laypat = self._infer_laypat()
        glue   = self._infer_glue()
        grout  = self._infer_grout()
        # уровень 5 (единый итог)
        solution = self._infer_solution(laypat, glue, grout)

        recs = []
        d = self.derived
        recs.append(f"[DIFFIC*]    Сложность рисунка: {d['DIFFIC']}")
        recs.append(f"[ELAST*]     Эластичность клея: {d['ELAST']}")
        recs.append(f"[WETENV*]    Влажность среды:   {d['WETENV']}")
        recs.append(f"[SKILLREQ*]  Требуемый уровень мастерства: {d['SKILLREQ']}")
        recs.append(f"[GLUECLASS*] Класс клея:        {d['GLUECLASS']}")
        recs.append(f"[HYDRO*]     Гидроизоляция:     {d['HYDRO']}")
        recs.append(f"[COSTLEVEL*] Стоимость проекта: {d['COSTLEVEL']}")
        recs.append(f"[BUDGETFIT*] Соответствие бюджета: {d['BUDGETFIT']}")
        recs.append(f"[NEEDPRO*]   Профессионал:      {d['NEEDPRO']}")
        recs.append("─" * 70)
        recs.append(f"[LAYPAT*] Способ укладки: {laypat}")
        recs.append(f"[GLUE*]   Тип клея:       {glue}")
        recs.append(f"[GROUT*]  Тип затирки:    {grout}")
        recs.append("═" * 70)
        recs.append(f"[SOLUTION*] {solution}")
        return recs

